/** Helper to localize a full quiz object according to chosen language */
export const localizeQuiz = (quiz, locale) => {
  if (!quiz) return quiz;
  if (!locale || locale === 'en') return quiz;

  const tr = QUIZ_TRANSLATIONS[quiz.id]?.[locale];
  if (!tr) return quiz;

  const localizedQuestions = (quiz.questions ?? []).map((q, idx) => {
    const qTr = tr.questions?.[idx];
    if (!qTr) return q;

    return {
      ...q,
      prompt: qTr.prompt ?? q.prompt ?? q.question,
      options: qTr.options ?? q.options,
      hint: qTr.hint ?? q.hint,
      explanation: qTr.explanation ?? q.explanation,
      correctText: qTr.correctText ?? q.correctText,
      pairs: qTr.pairs ?? q.pairs
    };
  });

  return {
    ...quiz,
    title: tr.title ?? quiz.title,
    description: tr.description ?? quiz.description,
    questions: localizedQuestions
  };
};
