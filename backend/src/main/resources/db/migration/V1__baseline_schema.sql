-- ShikshaSetu baseline schema (PostgreSQL; also runs on H2 in PostgreSQL mode for local dev).
-- Derived from the JPA entities; Hibernate runs with ddl-auto=validate, so any entity change
-- needs a new V<n>__*.sql migration.

-- ---------------------------------------------------------------- users & profiles
create table users (
    id                 bigint generated by default as identity primary key,
    email              varchar(160) not null,
    password_hash      varchar(100) not null,
    name               varchar(120) not null,
    role               varchar(16)  not null,
    preferred_language varchar(8),
    active             boolean      not null,
    created_at         timestamp(6) with time zone not null,
    last_login_at      timestamp(6) with time zone,
    constraint uk_users_email unique (email),
    constraint ck_users_role check (role in ('STUDENT', 'TEACHER', 'ADMIN'))
);

create table student_profiles (
    id               bigint generated by default as identity primary key,
    user_id          bigint  not null,
    teacher_id       bigint,
    grade_level      integer,
    school           varchar(160),
    district         varchar(120),
    onboarded        boolean not null,
    xp               integer not null,
    current_streak   integer not null,
    longest_streak   integer not null,
    last_active_date date,
    constraint uk_student_profiles_user unique (user_id),
    constraint fk_student_profiles_user foreign key (user_id) references users (id),
    constraint fk_student_profiles_teacher foreign key (teacher_id) references users (id)
);
create index ix_student_profiles_teacher on student_profiles (teacher_id);

-- ---------------------------------------------------------------- curriculum
create table subjects (
    id          bigint generated by default as identity primary key,
    code        varchar(40)  not null,
    name        varchar(120) not null,
    description varchar(500),
    icon        varchar(40),
    color       varchar(16),
    grade_level integer,
    constraint uk_subjects_code unique (code)
);

create table chapters (
    id          bigint generated by default as identity primary key,
    subject_id  bigint       not null,
    title       varchar(160) not null,
    description varchar(500),
    position    integer      not null,
    constraint fk_chapters_subject foreign key (subject_id) references subjects (id)
);
create index ix_chapters_subject on chapters (subject_id);

create table lessons (
    id               bigint generated by default as identity primary key,
    chapter_id       bigint         not null,
    title            varchar(160)   not null,
    topic            varchar(80)    not null,
    summary          varchar(500),
    content          varchar(20000) not null,
    video_url        varchar(300),
    duration_minutes integer        not null,
    position         integer        not null,
    constraint fk_lessons_chapter foreign key (chapter_id) references chapters (id)
);
create index ix_lessons_chapter on lessons (chapter_id);

create table quizzes (
    id                 bigint generated by default as identity primary key,
    chapter_id         bigint       not null,
    title              varchar(160) not null,
    description        varchar(500),
    time_limit_seconds integer      not null,
    constraint fk_quizzes_chapter foreign key (chapter_id) references chapters (id)
);
create index ix_quizzes_chapter on quizzes (chapter_id);

create table questions (
    id            bigint generated by default as identity primary key,
    quiz_id       bigint        not null,
    prompt        varchar(1000) not null,
    topic         varchar(80)   not null,
    explanation   varchar(1000),
    correct_index integer       not null,
    position      integer       not null,
    constraint fk_questions_quiz foreign key (quiz_id) references quizzes (id)
);
create index ix_questions_quiz on questions (quiz_id);

create table question_options (
    question_id  bigint       not null,
    option_index integer      not null,
    option_text  varchar(500) not null,
    primary key (option_index, question_id),
    constraint fk_question_options_question foreign key (question_id) references questions (id)
);

-- ---------------------------------------------------------------- learning activity
create table lesson_progress (
    id                  bigint generated by default as identity primary key,
    student_id          bigint  not null,
    lesson_id           bigint  not null,
    completed_at        timestamp(6) with time zone not null,
    synced_from_offline boolean not null,
    constraint uk_lesson_progress_student_lesson unique (student_id, lesson_id),
    constraint fk_lesson_progress_student foreign key (student_id) references users (id),
    constraint fk_lesson_progress_lesson foreign key (lesson_id) references lessons (id)
);

create table quiz_attempts (
    id                  bigint generated by default as identity primary key,
    student_id          bigint  not null,
    quiz_id             bigint  not null,
    client_attempt_id   varchar(64),
    correct_count       integer not null,
    total_questions     integer not null,
    percentage          integer not null,
    xp_earned           integer not null,
    time_taken_seconds  integer,
    synced_from_offline boolean not null,
    submitted_at        timestamp(6) with time zone not null,
    constraint uk_quiz_attempts_client unique (student_id, client_attempt_id),
    constraint fk_quiz_attempts_student foreign key (student_id) references users (id),
    constraint fk_quiz_attempts_quiz foreign key (quiz_id) references quizzes (id)
);
create index ix_quiz_attempts_quiz on quiz_attempts (quiz_id);

create table attempt_answers (
    id             bigint generated by default as identity primary key,
    attempt_id     bigint  not null,
    question_id    bigint  not null,
    selected_index integer,
    correct        boolean not null,
    constraint fk_attempt_answers_attempt foreign key (attempt_id) references quiz_attempts (id),
    constraint fk_attempt_answers_question foreign key (question_id) references questions (id)
);
create index ix_attempt_answers_attempt on attempt_answers (attempt_id);

-- ---------------------------------------------------------------- gamification
create table xp_transactions (
    id          bigint generated by default as identity primary key,
    student_id  bigint       not null,
    amount      integer      not null,
    source      varchar(20)  not null,
    ref_key     varchar(120) not null,
    description varchar(200) not null,
    created_at  timestamp(6) with time zone not null,
    constraint uk_xp_transactions_ref unique (student_id, ref_key),
    constraint ck_xp_transactions_source check (source in ('LESSON', 'QUIZ', 'MISSION')),
    constraint fk_xp_transactions_student foreign key (student_id) references users (id)
);

create table badges (
    id          bigint generated by default as identity primary key,
    code        varchar(40)  not null,
    name        varchar(80)  not null,
    description varchar(240) not null,
    icon        varchar(40),
    constraint uk_badges_code unique (code)
);

create table student_badges (
    id         bigint generated by default as identity primary key,
    student_id bigint not null,
    badge_id   bigint not null,
    earned_at  timestamp(6) with time zone not null,
    constraint uk_student_badges unique (student_id, badge_id),
    constraint fk_student_badges_student foreign key (student_id) references users (id),
    constraint fk_student_badges_badge foreign key (badge_id) references badges (id)
);

-- ---------------------------------------------------------------- recommendations & assignments
create table recommendations (
    id         bigint generated by default as identity primary key,
    student_id bigint           not null,
    lesson_id  bigint           not null,
    kind       varchar(16)      not null,
    source     varchar(40)      not null,
    reason     varchar(500)     not null,
    priority   double precision not null,
    created_at timestamp(6) with time zone not null,
    constraint fk_recommendations_student foreign key (student_id) references users (id),
    constraint fk_recommendations_lesson foreign key (lesson_id) references lessons (id)
);
create index ix_recommendations_student on recommendations (student_id);

create table assignments (
    id         bigint generated by default as identity primary key,
    teacher_id bigint       not null,
    student_id bigint,
    lesson_id  bigint,
    quiz_id    bigint,
    title      varchar(160) not null,
    note       varchar(500),
    due_date   date,
    created_at timestamp(6) with time zone not null,
    constraint fk_assignments_teacher foreign key (teacher_id) references users (id),
    constraint fk_assignments_student foreign key (student_id) references users (id),
    constraint fk_assignments_lesson foreign key (lesson_id) references lessons (id),
    constraint fk_assignments_quiz foreign key (quiz_id) references quizzes (id)
);
create index ix_assignments_teacher on assignments (teacher_id);
create index ix_assignments_student on assignments (student_id);
