-- School / class model: a class belongs to a school and has (at most) one teacher; students
-- belong to a class and whole-class assignments target a class. Existing students are moved
-- into classes by V5, and the old student_profiles.teacher_id link is dropped by V6.

create table schools (
    id       bigint generated by default as identity primary key,
    name     varchar(160) not null,
    district varchar(120),
    constraint uk_schools_name_district unique (name, district)
);

create table classrooms (
    id          bigint generated by default as identity primary key,
    school_id   bigint      not null,
    name        varchar(80) not null,
    grade_level integer,
    teacher_id  bigint,
    join_code   varchar(12) not null,
    created_at  timestamp(6) with time zone not null,
    constraint uk_classrooms_join_code unique (join_code),
    constraint fk_classrooms_school foreign key (school_id) references schools (id),
    constraint fk_classrooms_teacher foreign key (teacher_id) references users (id)
);
create index ix_classrooms_school on classrooms (school_id);
create index ix_classrooms_teacher on classrooms (teacher_id);

alter table student_profiles add column classroom_id bigint;
alter table student_profiles add constraint fk_student_profiles_classroom foreign key (classroom_id) references classrooms (id);
create index ix_student_profiles_classroom on student_profiles (classroom_id);

alter table assignments add column classroom_id bigint;
alter table assignments add constraint fk_assignments_classroom foreign key (classroom_id) references classrooms (id);
create index ix_assignments_classroom on assignments (classroom_id);
