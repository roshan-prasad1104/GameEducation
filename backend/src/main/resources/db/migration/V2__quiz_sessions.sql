-- Online quiz sessions: instant feedback is only returned for an answer that has been stored
-- (locked) here, so the per-question check can no longer be used to probe the answer key.

create table quiz_sessions (
    id           bigint generated by default as identity primary key,
    student_id   bigint not null,
    quiz_id      bigint not null,
    -- "studentId:quizId" while the session is open, null after submit: at most one open session per quiz
    open_key     varchar(64),
    started_at   timestamp(6) with time zone not null,
    submitted_at timestamp(6) with time zone,
    attempt_id   bigint,
    constraint uk_quiz_sessions_open_key unique (open_key),
    constraint uk_quiz_sessions_attempt unique (attempt_id),
    constraint fk_quiz_sessions_student foreign key (student_id) references users (id),
    constraint fk_quiz_sessions_quiz foreign key (quiz_id) references quizzes (id),
    constraint fk_quiz_sessions_attempt foreign key (attempt_id) references quiz_attempts (id)
);
create index ix_quiz_sessions_quiz on quiz_sessions (quiz_id);

create table quiz_session_answers (
    id             bigint generated by default as identity primary key,
    session_id     bigint  not null,
    question_id    bigint  not null,
    selected_index integer not null,
    correct        boolean not null,
    answered_at    timestamp(6) with time zone not null,
    constraint uk_quiz_session_answers unique (session_id, question_id),
    constraint fk_quiz_session_answers_session foreign key (session_id) references quiz_sessions (id),
    constraint fk_quiz_session_answers_question foreign key (question_id) references questions (id)
);
create index ix_quiz_session_answers_question on quiz_session_answers (question_id);
